export function formatHeaderDate(date, language = "en") {
  if (language !== "or") {
    return new Intl.DateTimeFormat("en-IN", {
      weekday: "long",
      day: "numeric",
      month: "long",
      year: "numeric",
    })
      .format(date)
      .toLocaleUpperCase("en-IN");
  }

  const day = String(date.getDate()).replace(
    /\d/g,
    (digit) => odiaDigits[Number(digit)],
  );
  const year = String(date.getFullYear()).replace(
    /\d/g,
    (digit) => odiaDigits[Number(digit)],
  );
  return `${odiaWeekdays[date.getDay()]}, ${day} ${odiaMonths[date.getMonth()]}, ${year}`;
}

